create extension if not exists "pgcrypto";

-- -------------------------------------------------------------
-- 1. Pengaturan (satu baris per akun)
-- -------------------------------------------------------------
create table if not exists public.settings (
  id                bigint generated by default as identity primary key,
  owner_id          uuid not null unique default auth.uid()
                    references auth.users(id) on delete cascade,
  nama_kost         text not null default 'Kost Saya',
  alamat            text not null default '',
  bank              text not null default 'BCA',
  nomor_rekening    text not null default '',
  atas_nama         text not null default '',
  whatsapp_admin    text not null default '',
  jatuh_tempo_hari  smallint not null default 5 check (jatuh_tempo_hari between 1 and 28),
  denda_per_hari    integer not null default 0 check (denda_per_hari >= 0),
  created_at        timestamptz not null default now()
);

-- -------------------------------------------------------------
-- 2. Kamar (nomor unik per pemilik)
-- -------------------------------------------------------------
create table if not exists public.rooms (
  id           uuid primary key default gen_random_uuid(),
  owner_id     uuid not null default auth.uid()
               references auth.users(id) on delete cascade,
  nomor        text not null,
  tipe         text not null default 'Standar',
  harga_sewa   integer not null default 0 check (harga_sewa >= 0),
  fasilitas    text not null default '',
  status       text not null default 'kosong'
               check (status in ('kosong', 'terisi', 'perbaikan')),
  created_at   timestamptz not null default now(),
  unique (owner_id, nomor)
);

-- -------------------------------------------------------------
-- 3. Penghuni
-- -------------------------------------------------------------
create table if not exists public.tenants (
  id              uuid primary key default gen_random_uuid(),
  owner_id        uuid not null default auth.uid()
                  references auth.users(id) on delete cascade,
  nama            text not null,
  no_hp           text not null default '',
  email           text not null default '',
  room_id         uuid references public.rooms(id) on delete set null,
  tanggal_masuk   date not null default current_date,
  tanggal_keluar  date,
  deposit         integer not null default 0 check (deposit >= 0),
  status          text not null default 'aktif'
                  check (status in ('aktif', 'keluar')),
  catatan         text not null default '',
  created_at      timestamptz not null default now()
);

-- -------------------------------------------------------------
-- 4. Tagihan (invoice) bulanan
--    total dihitung otomatis oleh database.
-- -------------------------------------------------------------
create table if not exists public.invoices (
  id            uuid primary key default gen_random_uuid(),
  owner_id      uuid not null default auth.uid()
                references auth.users(id) on delete cascade,
  tenant_id     uuid not null references public.tenants(id) on delete cascade,
  room_id       uuid references public.rooms(id) on delete set null,
  periode       date not null,
  jatuh_tempo   date not null,
  sewa          integer not null default 0 check (sewa >= 0),
  listrik       integer not null default 0 check (listrik >= 0),
  air           integer not null default 0 check (air >= 0),
  biaya_lain    integer not null default 0 check (biaya_lain >= 0),
  diskon        integer not null default 0 check (diskon >= 0),
  denda         integer not null default 0 check (denda >= 0),
  total         integer generated always as
                (sewa + listrik + air + biaya_lain + denda - diskon) stored,
  catatan       text not null default '',
  created_at    timestamptz not null default now(),
  unique (tenant_id, periode)
);

-- -------------------------------------------------------------
-- 5. Pembayaran / bukti transfer
-- -------------------------------------------------------------
create table if not exists public.payments (
  id             uuid primary key default gen_random_uuid(),
  owner_id       uuid not null default auth.uid()
                 references auth.users(id) on delete cascade,
  invoice_id     uuid not null references public.invoices(id) on delete cascade,
  jumlah         integer not null check (jumlah > 0),
  metode         text not null default 'transfer'
                 check (metode in ('transfer', 'tunai', 'qris', 'lainnya')),
  tanggal_bayar  date not null default current_date,
  pengirim       text not null default '',
  bukti_path     text,
  status         text not null default 'menunggu'
                 check (status in ('menunggu', 'valid', 'ditolak')),
  catatan        text not null default '',
  verified_by    text,
  verified_at    timestamptz,
  created_at     timestamptz not null default now()
);

create index if not exists settings_owner_idx on public.settings (owner_id);
create index if not exists rooms_owner_idx    on public.rooms (owner_id);
create index if not exists tenants_owner_idx  on public.tenants (owner_id);
create index if not exists invoices_owner_idx on public.invoices (owner_id);
create index if not exists payments_owner_idx on public.payments (owner_id);
create index if not exists invoices_periode_idx on public.invoices (periode);
create index if not exists invoices_tenant_idx on public.invoices (tenant_id);
create index if not exists payments_invoice_idx on public.payments (invoice_id);
create index if not exists payments_status_idx on public.payments (status);
create index if not exists tenants_room_idx on public.tenants (room_id);
create index if not exists tenants_status_idx on public.tenants (status);

-- -------------------------------------------------------------
-- 6. Row Level Security: hanya pemilik data yang boleh akses.
--    Halaman publik /bayar memakai service role di server.
-- -------------------------------------------------------------
alter table public.settings enable row level security;
alter table public.rooms    enable row level security;
alter table public.tenants  enable row level security;
alter table public.invoices enable row level security;
alter table public.payments enable row level security;

drop policy if exists "owner_settings" on public.settings;
create policy "owner_settings" on public.settings
  for all to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

drop policy if exists "owner_rooms" on public.rooms;
create policy "owner_rooms" on public.rooms
  for all to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

drop policy if exists "owner_tenants" on public.tenants;
create policy "owner_tenants" on public.tenants
  for all to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

drop policy if exists "owner_invoices" on public.invoices;
create policy "owner_invoices" on public.invoices
  for all to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

drop policy if exists "owner_payments" on public.payments;
create policy "owner_payments" on public.payments
  for all to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

-- -------------------------------------------------------------
-- 7. Akun baru otomatis mendapat pengaturan + 10 kamar sendiri
-- -------------------------------------------------------------
create or replace function public.handle_new_user_kostin()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.settings (owner_id)
  values (new.id)
  on conflict (owner_id) do nothing;

  -- 10 kamar standar sebagai titik awal. Pemilik bisa mengubah/menghapusnya.
  insert into public.rooms (owner_id, nomor, tipe, harga_sewa, fasilitas, status)
  select new.id, lpad(g::text, 2, '0'), 'Standar', 600000, '', 'kosong'
  from generate_series(1, 10) as t(g)
  on conflict (owner_id, nomor) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_kostin on auth.users;
create trigger on_auth_user_created_kostin
  after insert on auth.users
  for each row execute function public.handle_new_user_kostin();

-- Akun yang sudah ada sebelum skema ini dijalankan
insert into public.settings (owner_id)
select u.id
from auth.users u
left join public.settings s on s.owner_id = u.id
where s.owner_id is null;

-- -------------------------------------------------------------
-- 8. Storage untuk bukti transfer (bucket privat)
--    Path file: <owner_id>/<invoice_id>/<file>
-- -------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('bukti-transfer', 'bukti-transfer', false)
on conflict (id) do nothing;

drop policy if exists "bukti_insert_owner" on storage.objects;
create policy "bukti_insert_owner" on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'bukti-transfer'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

drop policy if exists "bukti_select_owner" on storage.objects;
create policy "bukti_select_owner" on storage.objects
  for select to authenticated
  using (
    bucket_id = 'bukti-transfer'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );

drop policy if exists "bukti_delete_owner" on storage.objects;
create policy "bukti_delete_owner" on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'bukti-transfer'
    and (storage.foldername(name))[1] = (select auth.uid()::text)
  );
